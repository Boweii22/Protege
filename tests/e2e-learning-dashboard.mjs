import {chromium} from 'playwright-core';

const url=process.env.PROTEGE_URL||'http://127.0.0.1:5177';
const browser=await chromium.launch({executablePath:'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe',headless:true});
const errors=[];const failed=[];
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('favicon'))errors.push(message.text())});
page.on('response',response=>{if(response.status()>=500)failed.push(`${response.status()} ${response.url()}`)});
await page.goto(url,{waitUntil:'networkidle'});
await page.getByRole('button',{name:/your learning map/i}).click();
await page.getByRole('heading',{name:/your knowledge leaves evidence/i}).waitFor();
const emptyNext=await page.getByText('Your first lesson',{exact:true}).isVisible();
await page.getByRole('button',{name:/start a lesson/i}).click();
await page.getByRole('button',{name:/negative × negative/i}).click();
await page.getByRole('button',{name:/begin the lesson/i}).click();
await page.getByLabel('Your explanation').waitFor();
await page.getByLabel('Your explanation').fill('A negative sign reverses direction. Multiplying by another negative reverses that reversal, so the result points in the original positive direction.');
await page.getByRole('button',{name:/send explanation/i}).click();
await page.locator('.messages article.student').nth(1).waitFor({timeout:30000});
await page.getByRole('button',{name:/test maya/i}).click();
await page.getByText('Maya scored').waitFor({timeout:30000});
await page.waitForFunction(()=>document.querySelector('.giant-score b')?.textContent===document.querySelector('.score-sheet footer span')?.textContent);
const score=await page.locator('.giant-score b').textContent();
await page.getByRole('button',{name:/start over/i}).click();
await page.getByRole('button',{name:/your learning map/i}).click();
await page.getByRole('heading',{name:/your knowledge leaves evidence/i}).waitFor();
const sessionCount=await page.locator('.dash-stats article').first().locator('strong').textContent();
const recentCount=await page.locator('.recent-list button').count();
await page.screenshot({path:'learning-dashboard-e2e.png',fullPage:true});
await page.locator('.recent-list button').first().click();
await page.getByText('Maya scored').waitFor();
await page.screenshot({path:'learning-dashboard-restored-e2e.png',fullPage:true});
const mobile=await browser.newPage({viewport:{width:390,height:844}});
mobile.on('pageerror',error=>errors.push(`mobile: ${error.message}`));
await mobile.goto(url,{waitUntil:'networkidle'});
await mobile.getByRole('button',{name:/your learning map/i}).click();
await mobile.getByRole('heading',{name:/your knowledge leaves evidence/i}).waitFor();
const mobileOverflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>document.documentElement.clientWidth);
await mobile.screenshot({path:'learning-dashboard-mobile-e2e.png',fullPage:true});
console.log(JSON.stringify({emptyNext,score,sessionCount,recentCount,mobileOverflow,errors,failed},null,2));
await browser.close();
if(!emptyNext||Number(sessionCount)<1||recentCount<1||mobileOverflow||errors.length||failed.length)process.exit(1);
